"""`traces/failures/INDEX.md`: one row per shipped failure, built from the diagnosis files.

AGENTS.md: "Failures are shipped, not hidden: `traces/failures/` with a one-line diagnosis each."
06-traces.md section 4 fixes that line's shape — four fields separated by ` · ` in the first line of
`<case>-s<seed>.diagnosis.txt` — and this module is the reader of it:

    uv run python -m evals.harness.failure_index

It walks `traces/failures/**/*.diagnosis.txt` and writes one table row per file: arm, case, seed,
stop condition, diagnosis. The index is generated, never edited, so it cannot fall behind the
directory; `--check` re-derives it and exits 1 when the committed file is stale.

The source is the diagnosis files rather than the failure traces beside them, which is what makes
this index a second opinion on `cells.failure_index` (that one walks the `.jsonl` files and writes
`README.md`): a diagnosis written for a trace that never got copied, or a trace whose diagnosis is
missing, shows up as a difference in row counts between the two files rather than in neither.

An empty failures directory is not an error. Before the first sweep, and after a sweep in which
every run was accepted, the index is a header and one sentence, and the exit code is 0.
"""

from __future__ import annotations

import argparse
import sys
from pathlib import Path

from evals.harness.plan import REPO_ROOT

DEFAULT_TRACES = "traces"
INDEX_NAME = "INDEX.md"
SEPARATOR = " · "
HEADER = ("| arm | case | seed | stop condition | diagnosis |", "|---|---|---|---|---|")
PREAMBLE = (
    "# Failure index\n\n"
    "Generated by `uv run python -m evals.harness.failure_index` from the `.diagnosis.txt` files\n"
    "in this directory; every run whose `stop_condition` was not `accepted` has one, beside a copy\n"
    "of its full trace (`docs/spec/06-traces.md` section 4). Do not edit by hand.\n\n")
EMPTY = "No failure traces recorded.\n"


def cell(text: str) -> str:
    """A table cell: no pipe may close the column it sits in, no newline may end the row."""
    return " ".join(str(text).replace("|", "\\|").split())


def identity(path: Path, root: Path) -> tuple[str, str, str]:
    """(arm, case, seed) from the file's place in the tree: `<root>/<arm>/<case>-s<seed>...`."""
    parts = path.relative_to(root).parts
    arm = parts[0] if len(parts) > 1 else ""
    stem = path.name[: -len(".diagnosis.txt")]
    case, _, seed = stem.rpartition("-s")
    return arm, (case or stem), seed


def row(path: Path, root: Path) -> tuple[str, str, int, str]:
    """One index row, plus the sort key. Fields the diagnosis line lacks render empty, not wrong."""
    arm, case, seed = identity(path, root)
    try:
        first = path.read_text(encoding="utf-8", errors="replace").split("\n", 1)[0]
    except OSError as exc:
        first = f"{SEPARATOR}unreadable{SEPARATOR}{type(exc).__name__}"
    fields = first.split(SEPARATOR)
    condition = fields[1] if len(fields) > 1 else ""
    diagnosis = SEPARATOR.join(f for f in fields[2:] if f.strip())
    line = (f"| {cell(arm)} | {cell(case)} | {cell(seed)} | {cell(condition)} "
            f"| {cell(diagnosis)} |")
    try:
        order = int(seed)
    except ValueError:
        order = 0
    return arm, case, order, line


def build(traces: Path) -> tuple[str, int]:
    """The index text and the number of failures in it. A missing directory is zero, not a raise."""
    root = traces / "failures"
    files = sorted(root.rglob("*.diagnosis.txt")) if root.is_dir() else []
    rows = sorted((row(path, root) for path in files), key=lambda r: (r[0], r[1], r[2]))
    if not rows:
        return PREAMBLE + EMPTY, 0
    body = "\n".join([*HEADER, *[r[3] for r in rows]])
    return PREAMBLE + body + "\n", len(rows)


def build_parser() -> argparse.ArgumentParser:
    parser = argparse.ArgumentParser(
        prog="evals.harness.failure_index",
        description="build traces/failures/INDEX.md from the diagnosis files")
    parser.add_argument("--traces", default=DEFAULT_TRACES, help="the traces root")
    parser.add_argument("--check", action="store_true",
                        help="do not write; exit 1 when the file on disk is not what this builds")
    return parser


def main(argv: list[str] | None = None) -> int:
    args = build_parser().parse_args(argv)
    traces = Path(args.traces)
    if not traces.is_absolute():
        traces = REPO_ROOT / traces
    text, count = build(traces)
    target = traces / "failures" / INDEX_NAME
    if args.check:
        current = target.read_text(encoding="utf-8") if target.is_file() else None
        if current == text:
            print(f"failure index OK: {count} failure(s)")
            return 0
        print(f"{target} is stale ({'absent' if current is None else 'differs'}); "
              "run `uv run python -m evals.harness.failure_index`", file=sys.stderr)
        return 1
    target.parent.mkdir(parents=True, exist_ok=True)
    target.write_text(text, encoding="utf-8")
    print(f"wrote {target} · {count} failure(s)")
    return 0


if __name__ == "__main__":  # pragma: no cover - module entry point
    sys.exit(main())
